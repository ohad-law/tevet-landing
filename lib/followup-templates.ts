/**
 * מחזיר את הודעת הפולואפ לשלב שנשלח כעת.
 * 1 = יום 1, 2 = יום 3, 3 = יום 7 והסוף.
 */
export function buildFollowupMessage(stage: number, fullName: string | null): string | null {
  const name = (fullName || '').split(' ')[0] || 'שלום'
  switch (stage) {
    case 1: return buildDay1(name)
    case 2: return buildDay3(name)
    case 3: return buildDay7(name)
    default: return null
  }
}

/**
 * מספר הימים מהפולואפ שנשלח עכשיו ועד הבא.
 * שלב 1 הוא יום 1, שלב 2 הוא יום 3, שלב 3 הוא יום 7 והסוף.
 */
export function daysUntilNextFollowup(stageJustSent: number): number | null {
  if (stageJustSent === 1) return 2   // מיום 1 ליום 3
  if (stageJustSent === 2) return 4   // מיום 3 ליום 7
  return null                          // אחרי יום 7 הרצף נגמר
}

/** מילים שמסמנות בקשת הסרה מהרצף */
export function isOptOut(text: string): boolean {
  const t = (text || '').trim().toLowerCase()
  return t === 'הסר' || t === 'הסרה' || t === 'הפסק' || t === 'הפסיקו' ||
         t === 'stop' || t === 'תפסיק' || t === 'הורד אותי'
}
