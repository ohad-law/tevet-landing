/** הקישור הרשמי לכתיבת ביקורת על הפרופיל בגוגל (נבדק ועובד) */
export const GOOGLE_REVIEW_LINK = 'https://g.page/r/Cf-b2dk5FCCuEBM/review'

/** שם פרטי בלבד, כדי שההודעה תישמע אישית ולא כמו טופס */
function firstName(fullName: string | null): string {
  const n = (fullName || '').trim().split(/\s+/)[0]
  return n || 'שלום'
}

export function buildReviewRequest(fullName: string | null): string {
  return [
    `${firstName(fullName)}, שלום 👋`,
    ``,
    `כאן אוהד טבת מהמשרד.`,
    `התיק שלך אצלנו הגיע לסיומו.`,
    ``,
    `אם היית מרוצה מהליווי, אשמח מאוד לביקורת קצרה בגוגל.`,
    `זה לוקח פחות מדקה, ועוזר לאנשים במצב דומה למצוא אותנו:`,
    ``,
    GOOGLE_REVIEW_LINK,
    ``,
    `תודה רבה, ובהצלחה 🙏`,
    `אוהד טבת, עו"ד`,
    ``,
    `(לא מעוניין בהודעות? השב "הסר")`,
  ].join('\n')
}
